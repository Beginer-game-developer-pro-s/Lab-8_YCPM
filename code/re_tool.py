#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
re_tool.py
Lab 8 - Safety-Critical Requirements, Tool Support & Final Integration
--------------------------------------------------------------------------
A simple command-line Requirements Management Tool that integrates ALL
the datasets built throughout the 8 labs: stakeholders,
functional/non-functional requirements, use cases, test cases, change
requests, and hazards.

Commands:
  - list <table>                 : list rows in a table
  - trace <ReqID>                : look up the traceability chain for a requirement
  - hazard-report                : safety hazard report with mitigations
  - coverage                     : % of FRs with test cases
  - export-summary               : export an overall project summary to Markdown

Examples:
  python3 re_tool.py list functional_requirements
  python3 re_tool.py trace FR-003
  python3 re_tool.py hazard-report
  python3 re_tool.py coverage
  python3 re_tool.py export-summary
"""
import csv
import os
import sys

BASE = os.path.join(os.path.dirname(__file__), "..", "datasets")

TABLES = {
    "stakeholders": "stakeholders.csv",
    "functional_requirements": "functional_requirements.csv",
    "nonfunctional_requirements": "nonfunctional_requirements.csv",
    "use_cases": "use_cases.csv",
    "test_cases": "test_cases.csv",
    "change_requests": "change_requests.csv",
    "hazards": "hazards.csv",
}


def load(table):
    with open(os.path.join(BASE, TABLES[table]), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def cmd_list(table):
    rows = load(table)
    for r in rows:
        key = list(r.keys())[0]
        name_key = list(r.keys())[1] if len(r.keys()) > 1 else key
        print(f"  {r[key]:<10} {r.get(name_key, '')}")
    print(f"\nTotal: {len(rows)} rows in table '{table}'")


def cmd_trace(req_id):
    frs = load("functional_requirements")
    ucs = {u["UseCaseID"]: u for u in load("use_cases")}
    tcs = load("test_cases")
    shs = {s["StakeholderID"]: s for s in load("stakeholders")}
    crs = load("change_requests")

    fr = next((f for f in frs if f["ReqID"] == req_id), None)
    if not fr:
        print(f"Requirement {req_id} not found")
        return

    print(f"=== Traceability for {req_id}: {fr['Title']} ===\n")
    sh = shs.get(fr["RelatedStakeholder"])
    print(f"Stakeholder: {fr['RelatedStakeholder']} - {sh['StakeholderName'] if sh else '?'}")
    uc = ucs.get(fr["RelatedUseCase"])
    print(f"Use case:    {fr['RelatedUseCase']} - "
          f"{uc['UseCaseName'] if uc else '(NOT FOUND - data error to fix)'}")
    related_tc = [t["TestCaseID"] for t in tcs if t["RelatedRequirement"] == req_id]
    print(f"Test case:   {', '.join(related_tc) if related_tc else '(NONE YET)'}")
    related_cr = [c["ChangeRequestID"] for c in crs if c["AffectedRequirement"] == req_id]
    print(f"Change req:  {', '.join(related_cr) if related_cr else '(none)'}")


def cmd_hazard_report():
    hazards = load("hazards")
    print("=== Safety Hazard Report ===\n")
    for h in hazards:
        print(f"[{h['HazardID']}] {h['HazardDescription']}")
        print(f"   Severity: {h['SeverityLevel']} | Overall risk: {h['OverallRisk']}")
        print(f"   Mitigation: {h['MitigationMeasure']}")
        print(f"   Related requirement(s): {h['RelatedRequirement']}\n")
    high = [h for h in hazards if h["OverallRisk"] == "High"]
    print(f">> {len(high)}/{len(hazards)} hazards are at HIGH RISK level and need priority action.")


def cmd_coverage():
    frs = load("functional_requirements")
    tcs = load("test_cases")
    covered_ids = {t["RelatedRequirement"] for t in tcs}
    covered = sum(1 for f in frs if f["ReqID"] in covered_ids)
    print(f"Functional requirement test coverage: {covered}/{len(frs)} "
          f"({100*covered/len(frs):.1f}%)")
    missing = [f["ReqID"] for f in frs if f["ReqID"] not in covered_ids]
    if missing:
        print(f"Still missing test cases for: {', '.join(missing)}")


def cmd_export_summary():
    frs, nfrs = load("functional_requirements"), load("nonfunctional_requirements")
    ucs, tcs = load("use_cases"), load("test_cases")
    shs, crs, hzs = load("stakeholders"), load("change_requests"), load("hazards")

    out = os.path.join(os.path.dirname(__file__), "project_summary.md")
    lines = [
        "# MedBook Project Summary (generated by re_tool.py)\n",
        f"- Stakeholders: {len(shs)}",
        f"- Functional requirements: {len(frs)}",
        f"- Non-functional requirements: {len(nfrs)}",
        f"- Use cases: {len(ucs)}",
        f"- Test cases: {len(tcs)}",
        f"- Change requests: {len(crs)} "
        f"(approved: {sum(1 for c in crs if c['Status']=='Approved')})",
        f"- Safety hazards: {len(hzs)} "
        f"(high risk: {sum(1 for h in hzs if h['OverallRisk']=='High')})",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\n[OK] Exported: {out}")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    cmd = sys.argv[1]
    if cmd == "list" and len(sys.argv) == 3:
        cmd_list(sys.argv[2])
    elif cmd == "trace" and len(sys.argv) == 3:
        cmd_trace(sys.argv[2])
    elif cmd == "hazard-report":
        cmd_hazard_report()
    elif cmd == "coverage":
        cmd_coverage()
    elif cmd == "export-summary":
        cmd_export_summary()
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
